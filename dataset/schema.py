from dataclasses import dataclass
from typing import Optional


@dataclass
class QECSample:
    """
    Standard schema for one QEC dataset sample.

    This class defines the structure of a single
    experiment generated by the QEC dataset pipeline.
    """

    # ---------------------------------
    # Experiment identification
    # ---------------------------------

    sample_id: int

    # ---------------------------------
    # Quantum configuration
    # ---------------------------------

    qec_code: str
    num_qubits: int
    logical_state: int

    # ---------------------------------
    # Physical quantum state
    # ---------------------------------

    original_state: str
    corrupted_state: str

    # ---------------------------------
    # Error information
    # ---------------------------------

    error_type: str
    error_qubit: Optional[int]
    error_description: str

    # ---------------------------------
    # Syndrome information
    # ---------------------------------

    syndrome: str

    # ---------------------------------
    # ML target
    # ---------------------------------

    target: Optional[int]